#!/usr/bin/env python3
"""soorat's generated tables: writes src/tables_data.cyr from tests/golden/tables.tsv (port plan §6.2, M1 part d).

    python3 -I -B scripts/oracle/gen_tables.py .           # write src/tables_data.cyr
    python3 -I -B scripts/oracle/gen_tables.py . --check   # exit 1 if it is stale

The sRGB-byte decode table is the `srgb8_decode_table` row's 256 f32: the decode of each byte's exact value b / 255,
correctly rounded, as scripts/oracle/validate.py's correctness reference writes the row (ADR 0003). Rust 1.2.0's table
rounded b / 255 to f32 first, and 214 of its entries were wrong (ADR 0002 #35). Stdlib only.
"""
import os
import sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else ".")
CHECK = "--check" in sys.argv


def decode_table():
    with open(os.path.join(ROOT, "tests", "golden", "tables.tsv"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("srgb8_decode_table\t"):
                outs = line.rstrip("\n").split("\t")[3].split(" ")
                vals = [int(t[2:], 16) for t in outs if t.startswith("g:")]
                if len(vals) != 256:
                    raise SystemExit(f"tables.tsv: srgb8_decode_table has {len(vals)} entries, not 256")
                return vals
    raise SystemExit("tables.tsv: no srgb8_decode_table row")


def text():
    vals = decode_table()
    out = [
        "# tables_data.cyr — GENERATED by scripts/oracle/gen_tables.py from tests/golden/tables.tsv. Do not edit.",
        "#",
        "# The linear value of each sRGB-encoded byte: the sRGB decode (IEC 61966-2-1) of its exact value b / 255,",
        "# correctly rounded to f32 (ADR 0003; 256 f32 bits). `_SR_SRGB8_DECODE` points to the static table, filled",
        "# once at load; read it through `_sr_srgb8_decode(b)` (src/tables.cyr).",
        "",
        "var _sr_srgb8_decode_data: u8[1024];",
        "var _SR_SRGB8_DECODE = &_sr_srgb8_decode_data;",
        "",
        "# Fills the table. Runs once, at load.",
        "fn _sr_srgb8_decode_init(): i64 {",
        "    var t = _SR_SRGB8_DECODE;",
    ]
    for i in range(0, 256, 3):
        out.append("    " + " ".join(f"store32(t + {4 * j}, 0x{vals[j]:08X});" for j in range(i, min(i + 3, 256))))
    out += ["    return 1;", "}", "var _sr_srgb8_decode_ready = _sr_srgb8_decode_init();", ""]
    return "\n".join(out)


def main():
    path = os.path.join(ROOT, "src", "tables_data.cyr")
    want = text()
    if CHECK:
        try:
            with open(path, encoding="utf-8") as f:
                stale = f.read() != want
        except FileNotFoundError:
            stale = True
        print("gen_tables:", "src/tables_data.cyr stale (run scripts/oracle/gen_tables.py .)" if stale else "ok")
        return 1 if stale else 0
    with open(path, "w", encoding="utf-8") as f:
        f.write(want)
    print("wrote src/tables_data.cyr (256 entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
